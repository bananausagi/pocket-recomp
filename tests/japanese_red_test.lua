-- Japanese format boundaries and name/storage regressions; no ROM needed.
love = require('tests.love_stub')
local T=require('tests.harness')
local GameVersion=require('src.core.GameVersion')
local Extractor=require('src.import.RomExtractor')
local Boxes=require('src.pokemon.Boxes')
local Strings=require('src.core.Strings')
local Convert=require('src.save_convert.SaveConvert')
local Naming=require('src.ui.NamingScreen')
local function decoder(bytes, length)
  local manifest={language='ja',symbols={sample={0,0}},
    charmap={['128']='ア',['5']='ガ'},text={lengths={sample=length or #bytes}}}
  local extractor=Extractor.new(bytes,manifest)
  return function(subs) return extractor:decodeTextCommands(extractor:symbol('sample'),subs or {}) end
end
T.eq(GameVersion.forSha1('0623ad12f48c259447980d68bd85ddbf8204b2cd'),'red_jp','retail Japanese Red identity')
T.eq(GameVersion.forSha1('ea9bcae617fdf159b045185467ae58b2e4a48b9a'),'red','US identity unchanged')
T.check(GameVersion.forSha1(string.rep('0',40))==nil,'unknown ROM rejected')
T.eq(decoder(string.char(0,128,5,0x57))(),'アガ{DONE}','inline Japanese dialogue')
T.eq(decoder(string.char(0,128,0x50,8,0xCD,0xAB))(),'ア','text_asm boundary stops before code')
T.eq(decoder(string.char(0,128,0x50,0xCD),3)(),'ア','next-symbol boundary stops before code')
T.check(not pcall(decoder(string.char(0,128))),'unterminated text rejected')
T.check(not pcall(decoder(string.char(1,0,0,0x50))),'missing substitution rejected')
T.eq(decoder(string.char(1,0,0,0x50))({{1,'{RAM:wStringBuffer}'}}),'{RAM:wStringBuffer}{DONE}','dynamic name substitution')
local jp={version='red_jp'}; Boxes.ensure(jp)
T.eq(#jp.boxes,8,'eight Japanese boxes')
for i=1,30 do T.eq(Boxes.deposit(jp,{id=i}),1,'Japanese box capacity') end
T.eq(Boxes.deposit(jp,{}),2,'31st mon starts next box')
local us={version='red'}; Boxes.ensure(us)
T.eq(#us.boxes,12,'US box count unchanged')
T.eq(Boxes.capacity(us),20,'US capacity unchanged')
T.check(not Convert.importSupported('red_jp'),'reject incompatible cartridge SRAM import')
T.check(not Convert.exportSupported('red_jp'),'reject incompatible cartridge SRAM export')
T.check(Convert.importSupported('red'),'US SRAM still supported')
Strings.load({constants={language='ja'}})
T.eq(Strings('SAVE'),'レポート','native UI translation')
Strings.load({})
T.eq(Strings('SAVE'),'SAVE','language resets on version change')
local game={data={constants={language='ja'}},stack={pop=function() end}}
local naming=Naming.new(game,{maxLen=10})
T.eq(naming.maxLen,5,'Japanese nickname limit')
T.eq(naming:grid()[1][2],'か','kana grid')
naming.lower=true; T.eq(naming:grid()[1][2],'カ','katakana grid')
T.eq(Naming.new({data={constants={}}},{maxLen=10}).maxLen,10,'US nickname limit unchanged')
T.finish()
